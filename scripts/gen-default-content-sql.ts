/**
 * Generates supabase/migrations/20261119000100_v1_default_content.sql from
 * lib/legal/templates.ts. Run: npx tsx scripts/gen-default-content-sql.ts
 */
import { writeFileSync } from "node:fs";
import { DEFAULT_FAQ, PRIVACY_TEMPLATE, TERMS_TEMPLATE } from "../lib/legal/templates";

const TAG = "$fz$";
const q = (s: string) => {
  if (s.includes(TAG)) throw new Error("Content contains the dollar-quote tag");
  return `${TAG}${s}${TAG}`;
};

const rows = DEFAULT_FAQ.map((f, i) => `      (${q(f.category)}, ${q(f.question)}, ${q(f.answer)}, ${i + 1}, true)`).join(",\n");

const sql = `-- ============================================================
-- Fight Zone V1 — default public content (generated by
-- scripts/gen-default-content-sql.ts from lib/legal/templates.ts).
-- Publishes Privacy v1 / Terms v1 and the FAQ ONLY when none exist yet,
-- so it never overwrites anything Seif already wrote.
-- ============================================================

insert into public.legal_documents (kind, version, title, content, status, published_at)
select 'privacy', 1, 'Privacy Policy', ${q(PRIVACY_TEMPLATE)}, 'PUBLISHED', now()
where not exists (select 1 from public.legal_documents where kind = 'privacy');

insert into public.legal_documents (kind, version, title, content, status, published_at)
select 'terms', 1, 'Terms of Use', ${q(TERMS_TEMPLATE)}, 'PUBLISHED', now()
where not exists (select 1 from public.legal_documents where kind = 'terms');

insert into public.faq_items (category, question, answer, position, is_published)
select v.category, v.question, v.answer, v.position, v.is_published
from (values
${rows}
) as v(category, question, answer, position, is_published)
where not exists (select 1 from public.faq_items);
`;

writeFileSync(new URL("../supabase/migrations/20261119000100_v1_default_content.sql", import.meta.url), sql);
console.log("written");
